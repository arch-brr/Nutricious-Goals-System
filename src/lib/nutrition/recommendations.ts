/**
 * Helper to get recommended foods filtered by user's dietary preference and optional meal slot
 */
export function getRecommendedFoods(
  dietPreference?: string | null,
  slot?: MealSlot | "all"
): RecommendedFood[] {
  const normDiet = (dietPreference || "mediterranean").toLowerCase();
  
  // Filter by diet preference first
  let matches = RECOMMENDED_FOODS_CATALOG.filter((f) => f.diet === normDiet);
  
  // Fallback to mediterranean if unknown diet
  if (matches.length === 0) {
    matches = RECOMMENDED_FOODS_CATALOG.filter((f) => f.diet === "mediterranean");
  }

  // Filter by slot if requested
  if (slot && slot !== "all") {
    const slotMatches = matches.filter((f) => f.slot === slot);
    if (slotMatches.length > 0) return slotMatches;
  }

  return matches;
}
